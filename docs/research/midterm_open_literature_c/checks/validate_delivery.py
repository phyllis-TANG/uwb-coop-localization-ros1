#!/usr/bin/env python3
"""Documentation/source-identity checks only. Does not run analytic examples."""
import argparse
import ast
import concurrent.futures
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.error
import urllib.parse
import urllib.request

parser = argparse.ArgumentParser()
parser.add_argument("--pandoc", required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
repo = root.parents[2]
allowed = "docs/research/midterm_open_literature_c/"
base = "0c3dbbb59a5c65087e073ad1c49eaed397f2958b"
report_path = root / "checks/DELIVERY_CHECKS.json"
failures = []

def run(*cmd, cwd=repo):
    return subprocess.check_output(cmd, cwd=cwd, text=True)

def walk(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from walk(child)
    elif isinstance(value, list):
        for child in value:
            yield from walk(child)

links = []
markdown = []
for path in sorted(root.rglob("*.md")):
    proc = subprocess.run(
        [args.pandoc, "-f", "markdown+tex_math_dollars", "-t", "json", str(path)],
        text=True, capture_output=True
    )
    if proc.returncode or proc.stderr:
        failures.append({"file": str(path.relative_to(root)), "pandoc": proc.stderr})
        continue
    markdown.append(str(path.relative_to(root)))
    for item in walk(json.loads(proc.stdout)):
        if item.get("t") in ("Link", "Image"):
            links.append((path, item["c"][-1][0]))

bib = json.loads(run(args.pandoc, "-f", "bibtex", "-t", "csljson",
                     str(root / "REFERENCES.bib")))
expected_bib = {
    "Calafiore2026", "Duembgen2023SafeSmooth", "ZhuKia2022UWB",
    "GarciaCrespillo2020GMP", "Papalia2024CORA", "ZhuKia2019Connectivity"
}
if {x["id"] for x in bib} != expected_bib:
    failures.append("Bibliography identity mismatch")

json_files = []
for path in sorted(root.rglob("*.json")):
    if path == report_path:
        continue
    json.loads(path.read_text())
    json_files.append(str(path.relative_to(root)))
for path in root.rglob("*.py"):
    ast.parse(path.read_text(), filename=str(path))

results = json.loads((root / "checks/RESULTS.json").read_text())
for filename, key in [
    ("CHECK_PROTOCOL.md", "protocol_sha256"),
    ("checks/analytic_checks.py", "script_sha256")
]:
    if hashlib.sha256((root / filename).read_bytes()).hexdigest() != results[key]:
        failures.append(f"Hash changed after execution: {filename}")
if (results["example_count"], results["optimizer_calls"], results["random_draws"]) != (3, 0, 0):
    failures.append("Unexpected example or run count")
protocol_from_commit = subprocess.check_output([
    "git", "show", results["protocol_commit"] + ":" + allowed + "CHECK_PROTOCOL.md"
], cwd=repo)
if hashlib.sha256(protocol_from_commit).hexdigest() != results["protocol_sha256"]:
    failures.append("Protocol commit does not match executed protocol")

source_repos = {
    "phyllis-TANG/uwb-coop-localization-ros1": repo,
    "utiasASRL/safe_and_smooth": Path("/tmp/open-certification-c/safe_and_smooth"),
    "MarineRoboticsGroup/cora": Path("/tmp/open-certification-c/cora"),
}
local_checks, fixed_git_checks, web_urls = [], [], set()
for source, link in links:
    if link.startswith("#") or link.startswith("mailto:"):
        continue
    url = urllib.parse.urlparse(link)
    if not url.scheme:
        target = (source.parent / urllib.parse.unquote(url.path)).resolve()
        # The report is generated by this command after the checks.
        if not target.exists() and target != report_path:
            failures.append(f"Missing local link: {source.name}: {link}")
        local_checks.append(link)
        continue
    match = re.match(r"^/([^/]+/[^/]+)/blob/([0-9a-f]{40})/(.+)$", url.path)
    if url.netloc == "github.com" and match and match[1] in source_repos:
        project, sha, path = match.groups()
        try:
            content = run("git", "show", f"{sha}:{path}", cwd=source_repos[project])
            anchor = re.fullmatch(r"L(\d+)(?:-L(\d+))?", url.fragment)
            if anchor and max(int(x) for x in anchor.groups() if x) > len(content.splitlines()):
                raise ValueError("line anchor beyond source")
            fixed_git_checks.append(link)
        except (subprocess.CalledProcessError, ValueError) as exc:
            failures.append(f"Fixed source invalid: {link}: {exc}")
    elif url.scheme in ("https", "http"):
        web_urls.add(link)

def check_web(url):
    request = urllib.request.Request(url, method="HEAD", headers={"User-Agent": "Mozilla/5.0"})
    try:
        with urllib.request.urlopen(request, timeout=12) as response:
            return {"url": url, "status": response.status, "final_url": response.url}
    except urllib.error.HTTPError as exc:
        return {"url": url, "status": exc.code, "result": "access restricted or endpoint rejected HEAD" if exc.code in (401, 403, 405, 429) else "HTTP error"}
    except Exception as exc:
        return {"url": url, "status": None, "result": type(exc).__name__ + ": " + str(exc)}

with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    web_checks = list(pool.map(check_web, sorted(web_urls)))
for check in web_checks:
    if check["status"] in (404, 410):
        failures.append({"dead_external_link": check})

scope = []
changed = run("git", "diff", "--name-status", base, "--").splitlines()
for line in changed:
    status, path = line.split("\t", 1)
    scope.append({"status": status, "path": path})
    if status != "A" or not path.startswith(allowed):
        failures.append(f"Outside additions-only scope: {line}")
for path in run("git", "ls-files", "--others", "--exclude-standard").splitlines():
    scope.append({"status": "untracked new", "path": path})
    if not path.startswith(allowed):
        failures.append(f"Outside allowed path: {path}")
if any(p.suffix.lower() in (".pdf", ".png", ".jpg", ".zip") for p in root.rglob("*") if p.is_file()):
    failures.append("Unexpected fulltext/image/archive artifact")
subprocess.run(["git", "diff", "--check", base, "--"], cwd=repo, check=True)

report = {
    "date_utc": "2026-11-17",
    "purpose": "Documentation validation, no localization or numerical examples executed",
    "base_main_sha": base,
    "remote_main_at_check": run("git", "rev-parse", "origin/main").strip(),
    "markdown_parsed": markdown,
    "bib_keys": sorted(expected_bib),
    "json_parsed": json_files,
    "python_AST_only": True,
    "registered_check_artifact_hashes_and_protocol_commit_verified": True,
    "local_links_checked": len(local_checks),
    "fixed_sha_links_checked": sorted(set(fixed_git_checks)),
    "external_HEAD_checks": web_checks,
    "source_scope": scope,
    "copyright_fulltext_or_author_source_added": False,
    "failures": failures,
    "limitations": [
        "HEAD restrictions/timeouts are not proof of missing pages; manuscript accesses recorded separately",
        "Markdown parsing and paper review are not TeX/PDF compilation",
        "Author libraries were not executed; no localization or Monte Carlo",
        "No probability validation inferred from three exact algebra cases"
    ]
}
report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
print(json.dumps({
    "markdown": len(markdown), "bibliography": len(bib),
    "local_links": len(local_checks), "fixed_git_links": len(set(fixed_git_checks)),
    "external_urls": len(web_checks), "failures": failures,
    "non_200_external": [x for x in web_checks if x["status"] != 200]
}, ensure_ascii=False, indent=2))
raise SystemExit(bool(failures))
